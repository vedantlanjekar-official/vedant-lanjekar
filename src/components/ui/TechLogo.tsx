export function hasLogo(name: string) {
  return name in ICONS;
}

/** Returns null when no established logo exists; callers then show the name as a text wordmark. */
export function TechLogo({ name, size = 20, className }: { name: string; size?: number; className?: string }) {
  const Icon = ICONS[name];
  if (!Icon) return null;
  return <Icon size={size} className={className} aria-hidden="true" />;
}
